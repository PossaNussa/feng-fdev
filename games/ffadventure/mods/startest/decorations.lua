    ["default:dirt_with_grass"] = "default:permafrost_with_stones",
    ["default:dirt"]            = "default:permafrost",
}
local schematic_path = minetest.get_modpath("startest") .. "/schematics/"

local tundra_schematics = {
    {sidelen = 11, fill_ratio = 7.65e-06, file = "small_space_crystal_deposit.mts"},
    {sidelen = 22, fill_ratio = 8.5e-06,  file = "med_space_crystal_deposit.mts"},
    {sidelen = 9,  fill_ratio = 6.8e-06, file = "super_small_space_crystal_deposit.mts"},
    {sidelen = 9,  fill_ratio = 4.25e-06, file = "big_space_crystal_deposit.mts"},
    {sidelen = 11, fill_ratio = 6.8e-06, file = "small_dense_space_crystal_deposit.mts"},
    {sidelen = 22, fill_ratio = 5.95e-06, file = "medium_dense_space_crystal_deposit.mts"},
    {sidelen = 9,  fill_ratio = 8.5e-07, file = "medium_dense_space_crystal_deposit2.mts"},
    {sidelen = 9,  fill_ratio = 5.1e-06, file = "big_dense_space_crystal_deposit.mts"},
    {sidelen = 9,  fill_ratio = 4.25e-06, file = "big_dense_space_crystal_deposit2.mts"},
}

for _, s in ipairs(tundra_schematics) do
    minetest.register_decoration({
        deco_type    = "schematic",
        place_on     = {"default:permafrost_with_stones"},
        sidelen      = s.sidelen,
        fill_ratio   = s.fill_ratio,
        biomes       = {"tundra"},
        y_max        = 1000,
        y_min        = 1,
        schematic    = schematic_path .. s.file,
        replacements = tundra_replacements,
        flags        = "place_center_x, place_center_z",
        rotation     = "random",
    })
end

