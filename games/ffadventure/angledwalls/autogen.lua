for _, colour in ipairs({"white", "grey", "black", "red", "yellow", "green",
		"cyan", "blue", "magenta", "orange", "violet", "brown", "pink",
		"dark_grey", "dark_green"}) do
	LEGACY["bakedclay" .. colour:gsub("_", "")] = "bakedclay:" .. colour
end

local function register_legacy_aliases()
	for subname, source in pairs(LEGACY) do
		local variants = angledwalls.variants[source] or {}
		local diag = variants.diag or (core.registered_nodes[source] and source)
		local corner = variants.corner or diag
		if diag then
			core.register_alias("angledwalls:angled_wall" .. subname, diag)
			core.register_alias("angledwalls:low_angled_wall" .. subname, diag)
			core.register_alias("angledwalls:corner" .. subname, corner)
		end
	end
end

core.register_on_mods_loaded(function()
	if not settings:get_bool("angledwalls.autogen", true) then
		return
	end

	local shapes = {"diag"}
	if settings:get_bool("angledwalls.corner_shape", true) then
		shapes[#shapes + 1] = "corner"
	end
	local budget = tonumber(settings:get("angledwalls.max_variants")) or 12000
	local exact, wildcards = parse_list(settings:get("angledwalls.exclude"))

	local sources = {}
	for name, def in pairs(core.registered_nodes) do
		local modname = name:match("^([^:]+):")
		if not exact[name] and not wildcards[modname or ""]
				and angledwalls.is_eligible(name, def) then
			sources[#sources + 1] = name
		end
	end
	-- Sorted so that hitting the budget drops the same blocks on every start;
	-- otherwise variants would come and go between restarts and turn into
	-- unknown nodes in existing builds.
	table.sort(sources)

	local blocks, made, failed = 0, 0, 0
	for _, source in ipairs(sources) do
		if made + #shapes > budget then
			core.log("warning", "[angledwalls] variant budget of " .. budget ..
				" reached, " .. (#sources - blocks) .. " blocks left without " ..
				"angled variants (raise angledwalls.max_variants)")
			break
		end
		local ok = false
		for _, shape in ipairs(shapes) do
			local name, err = angledwalls.register_variant(source, shape)
			if name then
				made = made + 1
				ok = true
			else
				failed = failed + 1
				core.log("info", "[angledwalls] no " .. shape .. " variant for " ..
					source .. ": " .. err)
			end
		end
		if ok then
			blocks = blocks + 1
		end
	end

	register_legacy_aliases()

	core.log("action", "[angledwalls] " .. made .. " angled variants for " ..
		blocks .. " blocks (" .. #shapes .. " shapes, " .. failed .. " skipped)")
end)
