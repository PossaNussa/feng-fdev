-- Angled Walls: give every ordinary block in the game an angled variant.
--
-- This runs in register_on_mods_loaded, which is late enough to see the nodes of
-- every mod in the game and still early enough to register nodes of our own.
-- No mod dependencies are needed for a block to be covered.

local settings = core.settings

local function parse_list(str)
	local exact, wildcards = {}, {}
	for item in (str or ""):gmatch("[^,%s]+") do
		local modname = item:match("^([%w_]+):%*$")
		if modname then
			wildcards[modname] = true
		else
			exact[item] = true
		end
	end
	return exact, wildcards
end

